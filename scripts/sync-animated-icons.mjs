import { readFile, writeFile } from 'node:fs/promises';
import { loadComponent } from '../src/test-support/renderComponent.js';

// Reconcile the retained artwork with Gaudi's actual glyphs, including aliases.
const root = new URL('../src/icons/animated/', import.meta.url);
const { artwork } = JSON.parse(await readFile(new URL('sources.json', root), 'utf8'));
const { iconRegistry } = await loadComponent(new URL('../src/icons/index.jsx', import.meta.url));
const entries = [];
const metadata = {};
const draws = {};
const slugs = new Map();
for (const [name, Glyph] of Object.entries(iconRegistry).sort(([a], [b]) => a.localeCompare(b))) {
  if (!Glyph.displayName || !Glyph.render) continue;
  const nodes = Glyph.render({}, null)?.props?.iconNode;
  if (!nodes) continue;
  const canonical = Glyph.displayName;
  const slug = artwork[canonical];
  if (slug) {
    if (!slugs.has(slug)) slugs.set(slug, `artwork${slugs.size}`);
    entries.push(`  ${JSON.stringify(name)}: ${slugs.get(slug)},`);
  } else {
    draws[canonical] = nodes;
    entries.push(`  ${JSON.stringify(name)}: drawIcons[${JSON.stringify(canonical)}],`);
  }
  metadata[name] = { canonical, source: slug ? 'lucide-animated' : 'gaudi-draw', ...(slug ? { slug } : {}) };
}
const special = { rocket: 'AnimatedRocketPaths', 'refresh-cw': 'AnimatedRefreshCwPaths' };
const imports = [...slugs].map(([slug, symbol]) => special[slug]
  ? `import { ${special[slug]} as ${symbol} } from './${slug === 'rocket' ? 'Rocket' : 'RefreshCw'}.jsx';`
  : `const ${symbol} = lazy(() => import('./catalog/${slug}.jsx'));`).join('\n');
const files = {
  'registry.js': `// Generated by scripts/sync-animated-icons.mjs. See README.md.\n'use client';\nimport { lazy } from 'react';\nimport { createDrawIcon } from './drawIcon.jsx';\nimport { drawNodes } from './drawNodes.js';\n${imports}\nconst drawIcons = Object.fromEntries(Object.entries(drawNodes).map(([name, nodes]) => [name, createDrawIcon(nodes)]));\nexport const animatedIconRegistry = {\n${entries.join('\n')}\n};\nexport const animatedIconMetadata = ${JSON.stringify(metadata, null, 2)};\n`,
  'drawNodes.js': `// Original Lucide geometry (ISC). See LUCIDE-LICENSE.\nexport const drawNodes = ${JSON.stringify(draws, null, 2)};\n`
};
for (const [name, content] of Object.entries(files)) {
  const file = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== content) throw new Error(`Stale animated icon catalog: ${name}`);
  } else await writeFile(file, content);
}
console.log(`${entries.length} animated names, ${slugs.size} imported animations, ${Object.keys(draws).length} original draw glyphs.`);
