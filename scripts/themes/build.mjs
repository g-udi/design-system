// `pnpm themes:build` — theme artefacts from the sources of truth:
//   themes/theme.schema.json     JSON schema generated from src/themes/contract.js
//   themes/presets/<id>.json     "gaudi" extracted from src/tokens/tokens.css + generated presets
//   src/themes/presets.js        runtime module (presets + alias anchors), consumed by compileTheme
//   src/themes/themes.css        every preset compiled, for apps that ship all presets statically
// Registry items (public/r/theme-<id>.json) are written by `pnpm registry:build`.
// Deterministic; `--check` fails when any output is stale or a preset misses WCAG AA.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { checkContrast, formatContrastReport } from '../../src/themes/contrast.js';
import { generateTheme } from '../../src/themes/generate.js';
import { validateTheme } from '../../src/themes/validate.js';
import { extractAnchors, extractDefaultTheme, root, themeSchema } from './extract.mjs';
import { presetRecipes } from './presets.mjs';

const check = process.argv.includes('--check');
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

const gaudi = extractDefaultTheme();
const presets = [gaudi, ...presetRecipes.map(({ seed, ...recipe }) => generateTheme({ ...recipe, seed }))];
const problems = [];
for (const theme of presets) {
  const { valid, errors } = validateTheme(theme);
  if (!valid) problems.push(`${theme.id}: ${errors.join(' ')}`);
  const report = checkContrast(theme);
  if (!report.pass) problems.push(`${theme.id}: ${formatContrastReport(report)}`);
}
if (problems.length) throw new Error(`Theme presets are invalid:\n${problems.join('\n')}`);

const anchors = extractAnchors();
const presetsModule = [
  '// Generated by `pnpm themes:build` from src/tokens/tokens.css, src/tokens/theme.css and',
  '// scripts/themes/presets.mjs. Do not edit; run the build instead.',
  '',
  '/** Declarations aliasing contract tokens, re-declared inside themed scopes. */',
  `export const ANCHOR_DECLARATIONS = ${JSON.stringify(anchors, null, 2)};`,
  '',
  '/** Shipped themes; the first is the default ("gaudi", identical to tokens.css). */',
  `export const themePresets = ${JSON.stringify(presets, null, 2)};`,
  ''
].join('\n');

const outputs = new Map([
  ['themes/theme.schema.json', json(themeSchema())],
  ['src/themes/presets.js', presetsModule],
  ...presets.map((theme) => [`themes/presets/${theme.id}.json`, json({ $schema: '../theme.schema.json', ...theme })])
]);

const stale = [];
const write = (file, content) => {
  const target = path.join(root, file);
  let current = null;
  try { current = readFileSync(target, 'utf8'); } catch { /* new file */ }
  if (current === content) return;
  if (check) { stale.push(file); return; }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, content);
};
for (const [file, content] of outputs) write(file, content);
for (const file of readdirSync(path.join(root, 'themes/presets'))) {
  if (outputs.has(`themes/presets/${file}`)) continue;
  if (check) stale.push(`themes/presets/${file}`);
  else rmSync(path.join(root, 'themes/presets', file));
}
if (!stale.length) {
  // compile.js reads presets.js, so load it fresh after writing.
  const { compileThemes } = await import(`${pathToFileURL(path.join(root, 'src/themes/compile.js')).href}?t=${Date.now()}`);
  write('src/themes/themes.css', `/* Generated by \`pnpm themes:build\`: every Gaudi theme preset. Set data-theme="<id>" on <html>. */\n${compileThemes(presets)}`);
}
if (stale.length) throw new Error(`Theme output is stale (${stale.join(', ')}). Run pnpm themes:build.`);
console.log(`Themes ${check ? 'are current' : 'written'}: ${presets.length} presets (${presets.map((theme) => theme.id).join(', ')}), ${anchors.length} anchors; all pass WCAG AA.`);
