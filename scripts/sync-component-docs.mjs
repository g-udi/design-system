import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Index authored owner metadata without making Storybook's module loader part of
// the documentation API. Node contracts and Storybook consume the same registry.
export const syncComponentDocs = async ({ check = false } = {}) => {
  const files = (await readdir(resolve(root, 'src/components'), { recursive: true }))
    .filter(file => /^[^/]+\/[^/]+\/stories\/docs\/[^/]+\.docs\.js$/.test(file))
    .sort();
  const imports = files.map((file, index) => `import docs${index} from '../../components/${file}';`).join('\n');
  const modules = files.map((file, index) => `  'src/components/${file}': docs${index}`).join(',\n');
  const output = `// Generated by pnpm catalogue:sync. Author documentation under each owner's stories/docs/.\n${imports}\n\nexport const ownerDocumentationModules = {\n${modules}\n};\n\nexport const ownerDocumentation = Object.assign({}, ...Object.values(ownerDocumentationModules));\n`;
  const destination = resolve(root, 'src/docs/catalogue/component-docs.js');
  if (check) {
    if (await readFile(destination, 'utf8') !== output) throw new Error('Component documentation index is stale. Run pnpm catalogue:sync.');
  } else {
    await writeFile(destination, output);
  }
  return files.length;
};
